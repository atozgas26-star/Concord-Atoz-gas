package com.example.export

import android.content.Context
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import java.io.File
import java.io.FileOutputStream
import java.io.OutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

data class ReportTable(
    val reportTitle: String,
    val subtitle: String,
    val generatedBy: String,
    val headers: List<String>,
    val rows: List<List<String>>,
    val footerTotals: List<String>? = null
)

object ReportExporter {

    fun createExportFile(context: Context, prefix: String, extension: String): File {
        val dir = File(context.cacheDir, "exports").apply { mkdirs() }
        val stamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())
        val safePrefix = prefix.lowercase(Locale.US).replace(Regex("[^a-z0-9]+"), "_")
        return File(dir, "${safePrefix}_$stamp.$extension")
    }

    fun writePdf(table: ReportTable, outputStream: OutputStream) {
        val pageWidth = 842 // A4 Landscape in points for spacious multi-column tables
        val pageHeight = 595
        val margin = 28f
        val contentWidth = pageWidth - margin * 2

        val pdf = PdfDocument()
        var pageNum = 1
        var page = pdf.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNum).create())
        var canvas = page.canvas

        val brandGreen = Paint().apply { color = Color.rgb(13, 110, 63) }
        val brandRed = Paint().apply { color = Color.rgb(200, 30, 30) }
        val headerBg = Paint().apply { color = Color.rgb(236, 253, 245) }
        val stripeBg = Paint().apply { color = Color.rgb(248, 250, 252) }
        val totalBg = Paint().apply { color = Color.rgb(254, 242, 242) }
        val borderPaint = Paint().apply {
            color = Color.rgb(203, 213, 225)
            strokeWidth = 0.8f
        }

        val companyPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.WHITE
            textSize = 14f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val titlePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(15, 23, 42)
            textSize = 13f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val metaPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(71, 85, 105)
            textSize = 9.5f
        }
        val thPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(5, 46, 22)
            textSize = 8.5f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val cellPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(15, 23, 42)
            textSize = 8.5f
        }
        val totalPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = Color.rgb(127, 29, 29)
            textSize = 8.8f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val colCount = table.headers.size.coerceAtLeast(1)
        val firstColWeight = 1.9f
        val otherWeight = 1.0f
        val totalWeight = if (colCount > 1) firstColWeight + (colCount - 1) * otherWeight else 1f
        val colWidths = List(colCount) { idx ->
            val weight = if (idx == 0 && colCount > 1) firstColWeight else otherWeight
            contentWidth * (weight / totalWeight)
        }

        fun drawBannerAndHeader(c: Canvas, pNum: Int): Float {
            c.drawRect(0f, 0f, pageWidth.toFloat(), 44f, brandGreen)
            c.drawRect(0f, 44f, pageWidth.toFloat(), 48f, brandRed)
            c.drawText("C&A GAS — Industrial & LPG Inventory", margin, 27f, companyPaint)
            val stamp = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.US).format(Date())
            val rightMeta = "Page $pNum • $stamp"
            val rightMetaPaint = Paint(companyPaint).apply {
                textSize = 9.5f
                typeface = Typeface.DEFAULT
            }
            val rightW = rightMetaPaint.measureText(rightMeta)
            c.drawText(
                rightMeta,
                pageWidth - margin - rightW,
                27f,
                rightMetaPaint
            )

            var y = 68f
            c.drawText(table.reportTitle, margin, y, titlePaint)
            y += 14f
            c.drawText("${table.subtitle}  |  Generated by: ${table.generatedBy}", margin, y, metaPaint)
            y += 12f

            // Table header row
            val rowH = 22f
            c.drawRect(margin, y, pageWidth - margin, y + rowH, headerBg)
            c.drawLine(margin, y, pageWidth - margin, y, borderPaint)
            var x = margin
            table.headers.forEachIndexed { idx, h ->
                val text = fitText(h, thPaint, colWidths[idx] - 6f)
                c.drawText(text, x + 3f, y + 14f, thPaint)
                x += colWidths[idx]
            }
            c.drawLine(margin, y + rowH, pageWidth - margin, y + rowH, borderPaint)
            return y + rowH
        }

        var y = drawBannerAndHeader(canvas, pageNum)
        val rowHeight = 19f

        table.rows.forEachIndexed { rowIdx, row ->
            if (y + rowHeight > pageHeight - 36f) {
                pdf.finishPage(page)
                pageNum++
                page = pdf.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNum).create())
                canvas = page.canvas
                y = drawBannerAndHeader(canvas, pageNum)
            }
            if (rowIdx % 2 == 1) {
                canvas.drawRect(margin, y, pageWidth - margin, y + rowHeight, stripeBg)
            }
            var x = margin
            row.forEachIndexed { idx, value ->
                if (idx < colWidths.size) {
                    val text = fitText(value, cellPaint, colWidths[idx] - 6f)
                    canvas.drawText(text, x + 3f, y + 13f, cellPaint)
                    x += colWidths[idx]
                }
            }
            canvas.drawLine(margin, y + rowHeight, pageWidth - margin, y + rowHeight, borderPaint)
            y += rowHeight
        }

        table.footerTotals?.let { totals ->
            if (y + 24f > pageHeight - 24f) {
                pdf.finishPage(page)
                pageNum++
                page = pdf.startPage(PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNum).create())
                canvas = page.canvas
                y = drawBannerAndHeader(canvas, pageNum)
            }
            canvas.drawRect(margin, y, pageWidth - margin, y + 22f, totalBg)
            var x = margin
            totals.forEachIndexed { idx, value ->
                if (idx < colWidths.size) {
                    val text = fitText(value, totalPaint, colWidths[idx] - 6f)
                    canvas.drawText(text, x + 3f, y + 14.5f, totalPaint)
                    x += colWidths[idx]
                }
            }
            canvas.drawLine(margin, y + 22f, pageWidth - margin, y + 22f, borderPaint)
        }

        pdf.finishPage(page)
        pdf.writeTo(outputStream)
        pdf.close()
    }

    /**
     * Writes a genuine OpenXML .xlsx Excel workbook using JDK ZipOutputStream (zero external POI bloat).
     */
    fun writeXlsx(table: ReportTable, outputStream: OutputStream) {
        val zip = ZipOutputStream(outputStream)

        fun addEntry(name: String, content: String) {
            zip.putNextEntry(ZipEntry(name))
            zip.write(content.toByteArray(Charsets.UTF_8))
            zip.closeEntry()
        }

        addEntry(
            "[Content_Types].xml",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
  <Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
  <Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
</Types>"""
        )

        addEntry(
            "_rels/.rels",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>"""
        )

        addEntry(
            "xl/_rels/workbook.xml.rels",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
  <Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>"""
        )

        addEntry(
            "xl/workbook.xml",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    <sheet name="Report" sheetId="1" r:id="rId1"/>
  </sheets>
</workbook>"""
        )

        addEntry(
            "xl/styles.xml",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <fonts count="3">
    <font><sz val="11"/><name val="Calibri"/></font>
    <font><b/><sz val="11"/><color rgb="FFFFFFFF"/><name val="Calibri"/></font>
    <font><b/><sz val="12"/><color rgb="FF0D6E3F"/><name val="Calibri"/></font>
  </fonts>
  <fills count="4">
    <fill><patternFill patternType="none"/></fill>
    <fill><patternFill patternType="gray125"/></fill>
    <fill><patternFill patternType="solid"><fgColor rgb="FF0D6E3F"/></patternFill></fill>
    <fill><patternFill patternType="solid"><fgColor rgb="FFFEE2E2"/></patternFill></fill>
  </fills>
  <borders count="1">
    <border><left/><right/><top/><bottom/><diagonal/></border>
  </borders>
  <cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>
  <cellXfs count="4">
    <xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/>
    <xf numFmtId="0" fontId="1" fillId="2" borderId="0" xfId="0" applyFont="1" applyFill="1"/>
    <xf numFmtId="0" fontId="2" fillId="0" borderId="0" xfId="0" applyFont="1"/>
    <xf numFmtId="0" fontId="2" fillId="3" borderId="0" xfId="0" applyFont="1" applyFill="1"/>
  </cellXfs>
</styleSheet>"""
        )

        val rowsXml = StringBuilder()
        var rowIndex = 1

        fun appendRow(values: List<String>, styleId: Int = 0, detectNumbers: Boolean = true) {
            rowsXml.append("<row r=\"$rowIndex\">")
            values.forEachIndexed { colIdx, raw ->
                val ref = "${colLetter(colIdx)}$rowIndex"
                val numVal = if (detectNumbers) raw.toDoubleOrNull() else null
                if (numVal != null && !raw.startsWith("0") || raw == "0") {
                    rowsXml.append("<c r=\"$ref\" s=\"$styleId\"><v>${xmlEscape(raw)}</v></c>")
                } else {
                    rowsXml.append(
                        "<c r=\"$ref\" s=\"$styleId\" t=\"inlineStr\"><is><t>${xmlEscape(raw)}</t></is></c>"
                    )
                }
            }
            rowsXml.append("</row>")
            rowIndex++
        }

        appendRow(listOf("C&A GAS — ${table.reportTitle}"), styleId = 2, detectNumbers = false)
        appendRow(listOf("${table.subtitle} | Generated by: ${table.generatedBy}"), styleId = 0, detectNumbers = false)
        rowIndex++ // Blank row 3
        appendRow(table.headers, styleId = 1, detectNumbers = false)
        table.rows.forEach { appendRow(it, styleId = 0, detectNumbers = true) }
        table.footerTotals?.let { appendRow(it, styleId = 3, detectNumbers = true) }

        val colsXml = StringBuilder("<cols>")
        table.headers.forEachIndexed { idx, _ ->
            val width = if (idx == 0) 28 else 15
            colsXml.append("<col min=\"${idx + 1}\" max=\"${idx + 1}\" width=\"$width\" customWidth=\"1\"/>")
        }
        colsXml.append("</cols>")

        addEntry(
            "xl/worksheets/sheet1.xml",
            """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  $colsXml
  <sheetData>$rowsXml</sheetData>
</worksheet>"""
        )

        zip.finish()
        zip.flush()
    }

    fun writePdfToFile(table: ReportTable, file: File) {
        FileOutputStream(file).use { writePdf(table, it) }
    }

    fun writeXlsxToFile(table: ReportTable, file: File) {
        FileOutputStream(file).use { writeXlsx(table, it) }
    }

    private fun fitText(text: String, paint: Paint, maxWidth: Float): String {
        if (paint.measureText(text) <= maxWidth) return text
        var end = text.length
        while (end > 1 && paint.measureText(text.substring(0, end) + "…") > maxWidth) {
            end--
        }
        return if (end <= 1) text.take(1) else text.substring(0, end) + "…"
    }

    private fun colLetter(index: Int): String {
        var n = index
        val sb = StringBuilder()
        while (n >= 0) {
            sb.insert(0, ('A' + (n % 26)))
            n = (n / 26) - 1
        }
        return sb.toString()
    }

    private fun xmlEscape(value: String): String =
        value.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "&quot;")
            .replace("'", "&apos;")
}
